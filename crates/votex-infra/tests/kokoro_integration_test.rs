use std::path::PathBuf;
use votex_domain::tts::provider::TtsProvider;

fn workspace_root() -> PathBuf {
    // ???CARGO_MANIFEST_DIR ?????????workspace root
    let mut dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    // crates/votex-infra ???.. ???workspace root
    dir.pop();
    dir.pop();
    dir
}

fn model_path() -> PathBuf {
    let mut p = workspace_root();
    p.push("models/kokoro-82m/kokoro-v1.0.int8.onnx");
    p
}

fn voice_path() -> PathBuf {
    let mut p = workspace_root();
    p.push("models/kokoro-82m/voices/af_bella.bin");
    p
}

#[test]
fn kokoro_tts_synthesize_real_audio() {
    let model_path = model_path();
    if !model_path.exists() {
        eprintln!("?????????????????????????????????????????????: {:?}", model_path);
        eprintln!("   ?????????Kokoro ONNX ??????????????????????????????");
        return;
    }

    let vpath = voice_path();
    if !vpath.exists() {
        eprintln!("?????????????????????????????????????????????: {:?}", vpath);
        return;
    }

    // 1. ?????? Provider
    let mut provider = votex_infra::tts::kokoro::KokoroProvider::new();
    assert!(!provider.is_loaded());

    // 2. ?????? ONNX ??????????????????????????????
    let model_path_str = model_path.to_string_lossy().to_string();
    let model = votex_domain::model::entity::Model::new(
        votex_domain::model::value_object::ModelId::new("kokoro-82m"),
        &model_path_str,
        votex_domain::model::value_object::ModelKind::Tts,
        votex_domain::model::value_object::EngineKind::Kokoro,
    );
    provider.load(&model).expect("?????? Kokoro ONNX ????????????");
    assert!(provider.is_loaded());
    eprintln!("?????????????????????");

    // 3. ????????????
    let voice = votex_domain::tts::value_object::VoiceId::new(
        "af_bella", "Bella", votex_domain::model::value_object::EngineKind::Kokoro,
    );
    let params = votex_domain::tts::value_object::TtsParams {
        engine: votex_domain::model::value_object::EngineKind::Kokoro,
        voice: voice.clone(),
        speed: votex_domain::tts::value_object::Speed::default(),
        pitch: votex_domain::tts::value_object::Pitch::default(),
        volume: votex_domain::tts::value_object::Volume::default(),
        segment_size: votex_domain::tts::value_object::SegmentSize::S500,
        segment_silence_ms: 500,
        crossfade_ms: 10,
        num_to_chinese: false,
        denoise: false,
        denoise_level: votex_domain::tts::value_object::DenoiseLevel::Low,
        emotion: None,
        dialect: None,
    };

    let test_text = "test TTS: hello world, this is a test";
    eprintln!("G2P ??????: '{}'", test_text);
    let phonemes = votex_infra::tts::kokoro_g2p::text_to_phonemes(test_text);
    eprintln!("   ???phonemes: '{}' (len={})", phonemes, phonemes.len());

    assert!(!phonemes.is_empty(), "G2P ??????????????????");

    let audio = provider.synthesize(test_text, &voice, &params)
        .expect("??????????????????");
    eprintln!("?????????????????????");
    eprintln!("   ????????? {} Hz", audio.sample_rate);
    eprintln!("   ????????? {}", audio.channels);
    eprintln!("   ????????? {}", audio.samples.len());
    eprintln!("   ??????: {} ms", audio.duration_ms());

    // 4. ????????????????????????
    let max_amplitude = audio.samples.iter()
        .map(|s: &f32| s.abs())
        .fold(0.0f32, f32::max);
    let rms = (audio.samples.iter()
        .map(|s: &f32| s * s)
        .sum::<f32>() / audio.samples.len() as f32)
        .sqrt();

    eprintln!("   ???????????? {:.6}", max_amplitude);
    eprintln!("   RMS: {:.6}", rms);

    // verify audio has valid signal
    assert!(max_amplitude > 0.001, "max amplitude too low: {}", max_amplitude);
    assert!(rms > 0.0001, "???????????????????????????RMS={}", rms);

    // 5. save result to WAV file
    let mut output_dir = workspace_root();
    output_dir.push("target/test_output");
    std::fs::create_dir_all(&output_dir).ok();
    let wav_path = output_dir.join("kokoro_test_output.wav");

    let spec = hound::WavSpec {
        channels: audio.channels,
        sample_rate: audio.sample_rate,
        bits_per_sample: 16,
        sample_format: hound::SampleFormat::Int,
    };
    let mut writer = hound::WavWriter::create(&wav_path, spec)
        .expect("?????? WAV ????????????");
    for &sample in &audio.samples {
        // f32 [-1,1] ???i16
        let amp = (sample * (i16::MAX as f32)).clamp(i16::MIN as f32, i16::MAX as f32) as i16;
        writer.write_sample(amp).ok();
    }
    writer.finalize().ok();
    eprintln!("?????????????????????: {:?}", wav_path);

    // 6. ????????????
    provider.unload().expect("??????????????????");
    assert!(!provider.is_loaded());
    eprintln!("provider unloaded successfully");
}
