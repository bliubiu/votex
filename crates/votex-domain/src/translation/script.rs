//! 中文简繁转换
//!
//! # 定位
//!
//! 用于翻译结果的书写系统归一：当目标语言是繁体中文（`zh-Hant` / `cht`）而引擎
//! 只产出简体时，做一次字形转换。
//!
//! # 覆盖范围
//!
//! 内置**常用字对照表**（约 500 组高频字），覆盖日常文本与绝大多数翻译场景。
//! 它是一个轻量实现，不追求收录全部异体字；如需完整覆盖可调用
//! [`ChineseConverter::with_extra_table`] 追加自定义映射。
//!
//! 一简对多繁的情况（如「发」→「發/髮」）取最常见字形，避免臆断词义。

use serde::{Deserialize, Serialize};
use std::collections::HashMap;

/// 中文书写系统
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum ChineseScript {
    /// 简体中文
    Simplified,
    /// 繁体中文
    Traditional,
    /// 不转换
    None,
}

impl Default for ChineseScript {
    fn default() -> Self {
        Self::None
    }
}

impl ChineseScript {
    /// 从语言代码推断书写系统
    ///
    /// 支持 `zh-Hans` / `zh-Hant` / `zh-cn` / `zh-tw` / `zh-hk` / `cht` / `chs` 等写法。
    pub fn from_lang_code(code: &str) -> Self {
        let lower = code.to_lowercase().replace('_', "-");
        if lower.contains("hant")
            || lower.contains("tw")
            || lower.contains("hk")
            || lower.contains("mo")
            || lower == "cht"
            || lower == "zh-tw"
            || lower == "zh-hk"
        {
            ChineseScript::Traditional
        } else if lower.contains("hans")
            || lower.contains("cn")
            || lower == "chs"
            || lower.starts_with("zh")
        {
            ChineseScript::Simplified
        } else {
            ChineseScript::None
        }
    }
}

/// 简繁转换器
#[derive(Debug, Clone)]
pub struct ChineseConverter {
    s2t: HashMap<char, char>,
    t2s: HashMap<char, char>,
}

impl Default for ChineseConverter {
    fn default() -> Self {
        Self::new()
    }
}

impl ChineseConverter {
    /// 使用内置常用字表创建转换器
    pub fn new() -> Self {
        let mut s2t = HashMap::new();
        let mut t2s = HashMap::new();
        for (s, t) in builtin_table() {
            s2t.insert(s, t);
            // 首次出现的繁体字建立反向映射，后续同形字不覆盖
            t2s.entry(t).or_insert(s);
        }
        Self { s2t, t2s }
    }

    /// 追加自定义映射表（条目格式：`[简, 繁]`）
    pub fn with_extra_table(mut self, pairs: &[(char, char)]) -> Self {
        for (s, t) in pairs {
            self.s2t.insert(*s, *t);
            self.t2s.entry(*t).or_insert(*s);
        }
        self
    }

    /// 转换文本到指定书写系统
    ///
    /// [`ChineseScript::None`] 直接返回原文。
    pub fn convert(&self, text: &str, script: ChineseScript) -> String {
        let table = match script {
            ChineseScript::Traditional => &self.s2t,
            ChineseScript::Simplified => &self.t2s,
            ChineseScript::None => return text.to_string(),
        };
        text.chars()
            .map(|c| table.get(&c).copied().unwrap_or(c))
            .collect()
    }
}

