#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 书写系统_从语言代码推断() {
        assert_eq!(ChineseScript::from_lang_code("zh-Hant"), ChineseScript::Traditional);
        assert_eq!(ChineseScript::from_lang_code("zh-TW"), ChineseScript::Traditional);
        assert_eq!(ChineseScript::from_lang_code("cht"), ChineseScript::Traditional);
        assert_eq!(ChineseScript::from_lang_code("zh-Hans"), ChineseScript::Simplified);
        assert_eq!(ChineseScript::from_lang_code("zh"), ChineseScript::Simplified);
        assert_eq!(ChineseScript::from_lang_code("en"), ChineseScript::None);
    }

    #[test]
    fn 简繁_简体转繁体() {
        let c = ChineseConverter::new();
        assert_eq!(c.convert("我们爱中国", ChineseScript::Traditional), "我們愛中國");
    }

    #[test]
    fn 简繁_繁体转简体() {
        let c = ChineseConverter::new();
        assert_eq!(c.convert("我們愛中國", ChineseScript::Simplified), "我们爱中国");
    }

    #[test]
    fn 简繁_不转换时原样返回() {
        let c = ChineseConverter::new();
        assert_eq!(c.convert("我们", ChineseScript::None), "我们");
    }

    #[test]
    fn 简繁_非汉字不受影响() {
        let c = ChineseConverter::new();
        assert_eq!(c.convert("Hello, 世界!", ChineseScript::Traditional), "Hello, 世界!");
    }

    #[test]
    fn 简繁_自定义映射表可追加() {
        let c = ChineseConverter::new().with_extra_table(&[('囍', '囍')]);
        assert_eq!(c.convert("囍", ChineseScript::Traditional), "囍");
    }
}
